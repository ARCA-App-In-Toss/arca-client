import { act, fireEvent, screen, waitFor } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { setupServer } from 'msw/node';
import { afterAll, afterEach, beforeAll, expect, test } from 'vitest';
import { SYNTHETIC_KEYS } from '../../mocks/world.ts';
import { bootApp, findTitle, opCount } from '../../test/boot.tsx';
import { copy } from '../../ui/copy.ts';

const server = setupServer();
beforeAll(() => server.listen({ onUnhandledRequest: 'error' }));
afterEach(() => server.resetHandlers());
afterAll(() => server.close());
const button = (name: string) => screen.getByRole('button', { name });
test('direct save preserves raw content, disables concurrent submission and displays server count', async () => {
  const b = bootApp(server);
  await act(() => b.started);
  await findTitle(copy['CPY-F10-001']);
  await userEvent.click(button(copy['CPY-F10-005']));
  await findTitle(copy['CPY-F11-001']);
  const field = await screen.findByRole('textbox', { name: copy['CPY-F11-003'] });
  await waitFor(() => expect(field).not.toHaveAttribute('readonly'));
  fireEvent.change(field, { target: { value: '  남길 기록\n' } });
  await userEvent.click(button(copy['CPY-F11-018']));
  await findTitle(copy['CPY-F12-001']);
  expect(b.world.answersOf(SYNTHETIC_KEYS.registered)[0]?.content).toBe('  남길 기록\n');
  expect(opCount(b.world, 'OP-006')).toBe(1);
  expect(screen.getByText('기억 조각 1개')).toBeInTheDocument();
});
test('failed network keeps draft and exposes explicit confirm/retry actions', async () => {
  const b = bootApp(server);
  await act(() => b.started);
  await findTitle(copy['CPY-F10-001']);
  await userEvent.click(button(copy['CPY-F10-005']));
  const field = await screen.findByRole('textbox', { name: copy['CPY-F11-003'] });
  await waitFor(() => expect(field).not.toHaveAttribute('readonly'));
  fireEvent.change(field, { target: { value: '보관할 기록' } });
  b.world.addFault('OP-006', { kind: 'network' });
  await userEvent.click(button(copy['CPY-F11-018']));
  await screen.findByText(/저장 결과를 확인하지 못했어요/);
  expect(field).toHaveValue('보관할 기록');
  await userEvent.click(button('다시 저장하기'));
  await findTitle(copy['CPY-F12-001']);
  expect(b.world.answers.size).toBe(1);
});
