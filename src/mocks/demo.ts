function archiveRecords(): DemoRecord[] {
  let seed = 20240701;
  const next = () => {
    seed = (seed * 1103515245 + 12345) % 2147483648;
    return seed / 2147483648;
  };
  const pick = (list: readonly string[]) => list[Math.floor(next() * list.length)] ?? '';
  const out: DemoRecord[] = [];
  for (const [month, count] of ARCHIVE_MONTHS) {
    const [year = 2026, monthNumber = 1] = month.split('-').map(Number);
    const lastDay = new Date(Date.UTC(year, monthNumber, 0)).getUTCDate();
    const days = new Set<number>();
    while (days.size < count) days.add(1 + Math.floor(next() * lastDay));
    for (const day of [...days].sort((a, b) => a - b)) {
      out.push({
        date: `${month}-${String(day).padStart(2, '0')}`,
        code: `SEMA-${String(out.length + 1).padStart(4, '0')}`,
        question: pick(QUESTION_POOL),
        answer: pick(ANSWER_POOL),
        edited: next() < 0.12,
      });
    }
  }
  return out;
}

